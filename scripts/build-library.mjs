// Builds the library's stories and poems from scripts/library/*.txt.
//   node scripts/build-library.mjs
// Each source file: "@key value" header lines (title.en, author.ko, source,
// license, ...), then pages separated by a line "===". A page is the Korean
// text, a line "---", then the English translation. A page may start with
// "# 한국어 제목 | English title". Writes public/library/<id>.json (the text,
// loaded when a book is opened) and src/data/library-shelf.js (just what the
// shelf needs, so the game bundle stays small).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';

const SRC = 'scripts/library';
const KINDS = ['children', 'story', 'poems'];

export function parseBook(text, file = '') {
  const [head, ...pageBlocks] = text.replace(/\r/g, '').split(/\n===\n/);
  const meta = {};
  for (const line of head.split('\n')) {
    const m = line.match(/^@([\w.]+)\s+(.*)$/);
    if (!m) continue;
    const [k, sub] = m[1].split('.');
    if (sub) (meta[k] ||= {})[sub] = m[2].trim();
    else meta[k] = m[2].trim();
  }
  for (const k of ['id', 'kind', 'icon', 'color', 'title', 'author', 'about', 'source', 'license']) {
    if (!meta[k]) throw new Error(`${file}: missing @${k}`);
  }
  if (!KINDS.includes(meta.kind)) throw new Error(`${file}: kind must be one of ${KINDS}`);
  const pages = pageBlocks.map((block, i) => {
    const parts = block.split(/\n---\n/);
    if (parts.length !== 2) throw new Error(`${file}: page ${i + 1} needs one "---" between Korean and English`);
    let [ko, en] = parts.map((s) => s.trim());
    let heading = null;
    const h = ko.match(/^# (.+?) \| (.+)\n/);
    if (h) { heading = { ko: h[1].trim(), en: h[2].trim() }; ko = ko.slice(h[0].length).trim(); }
    if (!ko || !en) throw new Error(`${file}: page ${i + 1} is missing text`);
    return heading ? { heading, ko, en } : { ko, en };
  });
  if (!pages.length) throw new Error(`${file}: no pages`);
  return { ...meta, pages };
}

function main() {
  const books = readdirSync(SRC).filter((f) => f.endsWith('.txt')).sort()
    .map((f) => parseBook(readFileSync(`${SRC}/${f}`, 'utf8'), f));
  mkdirSync('public/library', { recursive: true });
  for (const b of books) writeFileSync(`public/library/${b.id}.json`, JSON.stringify(b) + '\n');
  const order = (b) => KINDS.indexOf(b.kind);
  const shelf = books.sort((a, b) => order(a) - order(b))
    .map(({ id, kind, icon, color, title, author, pages }) => ({ id, kind, icon, color, title, author, pages: pages.length }));
  writeFileSync('src/data/library-shelf.js',
    '// Generated by scripts/build-library.mjs from scripts/library/*.txt. Do not edit by hand.\n' +
    '// Free stories and poems for the library: public-domain Korean works and retold folk tales.\n' +
    `export const LIBRARY = ${JSON.stringify(shelf, null, 1)};\n`);
  console.log(books.map((b) => `${b.id}: ${b.pages.length} pages`).join('\n'));
}

if (import.meta.url === `file://${process.argv[1]}`) main();
