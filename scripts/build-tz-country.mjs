// Builds src/data/tz-country.js: IANA time zone name → ISO country code, so
// the game can guess a player's country from the browser's time zone
// (core/country.js) without looking at their IP address.
// Source: the IANA time zone database installed with the system (public
// domain): zone.tab for each zone's country, tzdata.zi for old alias names
// (Asia/Calcutta, US/Eastern...) that some browsers still report.
//   node scripts/build-tz-country.mjs [/usr/share/zoneinfo]
import { readFileSync, writeFileSync } from 'node:fs';

const dir = process.argv[2] || '/usr/share/zoneinfo';
const version = (readFileSync(`${dir}/tzdata.zi`, 'utf8').match(/^# version (\S+)/m) || [])[1] || '?';
const map = {};
for (const line of readFileSync(`${dir}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , tz] = line.split('\t');
  map[tz] = cc;
}
// Aliases point at a zone; take that zone's country unless zone.tab names
// the alias itself (it does for countries that share a zone, like Vaduz).
for (const line of readFileSync(`${dir}/tzdata.zi`, 'utf8').split('\n')) {
  const m = line.match(/^L (\S+) (\S+)$/);
  if (m && map[m[1]] && !map[m[2]]) map[m[2]] = map[m[1]];
}
const keys = Object.keys(map).sort();
const body = keys.map((k) => `${k}=${map[k]}`).join(',');
writeFileSync(new URL('../src/data/tz-country.js', import.meta.url), `// Generated by scripts/build-tz-country.mjs from the IANA time zone database
// ${version} (public domain). Time zone → ISO 3166 country code. Don't edit by hand.
const RAW = '${body}';
export const TZ_COUNTRY = Object.fromEntries(RAW.split(',').map((p) => p.split('=')));
`);
console.log(`${keys.length} zones (tzdata ${version})`);
