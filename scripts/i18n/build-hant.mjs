// Builds src/i18n/hant.js: a simplified → traditional Chinese character map
// for the 繁體中文 option. It covers every character used in our Chinese
// (simplified) text: the zh block of src/i18n/strings.js and every `zh` field
// in src/ and public/. Each string is converted whole with OpenCC (cn → tw),
// and the most common result for each character is kept.
//
//   npm i --no-save opencc-js
//   node scripts/i18n/build-hant.mjs
// Run it again after adding Chinese text.
import * as OpenCC from 'opencc-js';
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';

const conv = OpenCC.Converter({ from: 'cn', to: 'tw' });
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.(js|mjs|json)$/.test(f)) files.push(p); } };
walk('src');
walk('public/regions');

const texts = [];
const HAN = /[㐀-鿿]/;
for (const f of files) {
  const src = readFileSync(f, 'utf8');
  // zh: '…' / "zh": "…" / zh: `…`
  for (const m of src.matchAll(/\bzh"?\s*:\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/g)) if (HAN.test(m[2])) texts.push(m[2]);
  if (f.endsWith('strings.js')) {
    const zh = src.slice(src.indexOf('\n  zh: {'), src.indexOf('\n  },', src.indexOf('\n  zh: {')));
    for (const m of zh.matchAll(/:\s*(['"`])((?:\\.|(?!\1)[^\\])*)\1/g)) if (HAN.test(m[2])) texts.push(m[2]);
  }
}
const votes = new Map(); // char -> Map(target -> n)
for (const s of texts) {
  const out = conv(s);
  const a = [...s], b = [...out];
  if (a.length !== b.length) continue;
  a.forEach((c, i) => {
    if (!HAN.test(c)) return;
    const v = votes.get(c) || new Map();
    v.set(b[i], (v.get(b[i]) || 0) + 1);
    votes.set(c, v);
  });
}
let pairs = '';
for (const [c, v] of [...votes].sort()) {
  const best = [...v].sort((x, y) => y[1] - x[1])[0][0];
  if (best !== c) pairs += c + best;
}
writeFileSync('src/i18n/hant.js', `// Simplified → traditional Chinese characters for the 繁體中文 option,
// generated by scripts/i18n/build-hant.mjs (OpenCC data, Apache-2.0).
// Pairs: each simplified character followed by its traditional one.
const PAIRS = '${pairs}';
const MAP = new Map();
for (let i = 0; i < PAIRS.length; i += 2) MAP.set(PAIRS[i], PAIRS[i + 1]);
// Phrases where the character-by-character answer is wrong.
const PHRASES = [['头发', '頭髮'], ['理发', '理髮'], ['染发', '染髮'], ['面条', '麵條'], ['拉面', '拉麵'], ['冷面', '冷麵'], ['炸酱面', '炸醬麵'], ['方便面', '方便麵'], ['面包', '麵包'], ['肉面', '肉麵'], ['汤面', '湯麵'], ['拌面', '拌麵'], ['冬面', '冬麵'], ['麦面', '麥麵'], ['米面', '米麵'], ['面线', '麵線'], ['面食', '麵食'], ['吃面', '吃麵'], ['碗面', '碗麵']];
export function s2t(s) {
  if (!s) return s;
  for (const [a, b] of PHRASES) if (s.includes(a)) s = s.split(a).join(b);
  let out = '';
  for (const c of s) out += MAP.get(c) || c;
  return out;
}
`);
console.log(texts.length, 'texts,', pairs.length / 2, 'characters');
