export function escapeChance(fish, spare = 0) {
  if (fish.trash) return 0;
  return [0, 0.10, 0.14, 0.18, 0.23, 0.28][fish.rarity] * (1 - 0.5 * Math.min(1, Math.max(0, spare)));
}

